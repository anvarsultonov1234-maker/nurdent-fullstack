export const formatPrice = (price: number, lang: Language): string => {
  if (price === 0) {
    return lang === 'uz' ? 'Kelishilgan narxda' : 'По согласованию';
  }
  const formatted = price.toLocaleString('ru-RU').replace(/,/g, ' ');
  return `${formatted} ${I18N[lang].currency}`;
};
